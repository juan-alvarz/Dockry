import AppKit
import DockryCore

/// Keeps a history of copied text, in memory only, while a clipboard widget is on screen.
/// macOS has no notification for clipboard changes, so this checks the pasteboard's change
/// counter twice a second, which is cheap.
@MainActor
final class ClipboardMonitor: ObservableObject {
    static let shared = ClipboardMonitor()

    @Published private(set) var history = ClipboardHistory()
    @Published var isShowingHistory = false

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var visibleWidgets = 0

    /// Markers password managers and similar apps put on what they copy, so clipboard tools
    /// leave it alone (see nspasteboard.org).
    private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    private init() {
        lastChangeCount = pasteboard.changeCount
    }

    /// Recording runs while at least one clipboard widget is showing, so nothing copied in a
    /// profile without the widget ends up in the history.
    func widgetAppeared() {
        visibleWidgets += 1
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount  // don't pick up what was copied while stopped
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            // Scheduled on the main run loop.
            MainActor.assumeIsolated { self?.checkForNewCopy() }
        }
    }

    func widgetDisappeared() {
        visibleWidgets -= 1
        guard visibleWidgets == 0 else { return }
        timer?.invalidate()
        timer = nil
        isShowingHistory = false
    }

    /// Puts `text` back on the clipboard, ready to paste.
    func copy(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        history.add(text)
        isShowingHistory = false
    }

    func clear() {
        history.removeAll()
    }

    private func checkForNewCopy() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.privateTypes), let text = pasteboard.string(forType: .string),
              // If something new (maybe private) was copied while reading, the text might be
              // from it; skip it, and the next check looks at the new copy properly.
              pasteboard.changeCount == changeCount
        else { return }
        history.add(text)
    }
}
